/**
 * Generate the human-readable architecture graph from the JSON declarations.
 *
 * Normal mode rewrites docs/architecture/module-graph.md. `--check` performs
 * no writes and fails when the checked-in graph is missing or stale.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadModuleMap, repositoryRoot } from "./lib/module-map.mjs";

const outputPath = path.join(repositoryRoot, "docs/architecture/module-graph.md");
const checkOnly = process.argv.includes("--check");

function renderGraph(modules, edges) {
  const lines = [
    "<!-- Generated by scripts/gen-module-graph.mjs. Do not edit by hand.",
    "     Run `npm.cmd run module-map:generate` to regenerate. -->",
    "",
    "# Module graph",
    "",
    "An arrow `A --> B` means module A depends on module B. Impact analysis walks the arrows in reverse, because changing B can affect A.",
    "",
    "```mermaid",
    "flowchart LR",
  ];
  for (const module of modules) {
    lines.push(`  ${module.id.replaceAll("-", "_")}[\"${module.name}\"]`);
  }
  for (const edge of edges) {
    const from = edge.from.replaceAll("-", "_");
    const to = edge.to.replaceAll("-", "_");
    lines.push(`  ${from} -->|${edge.type}| ${to}`);
  }
  lines.push("```", "", "## Modules", "", "| Module | Risk | Responsibility | Required gates |", "|---|---|---|---|");
  for (const module of modules) {
    lines.push(`| \`${module.id}\` | ${module.risk} | ${module.description} | ${module.gates.join("<br>") || "None"} |`);
  }
  lines.push("", "## Hidden or semantic dependencies", "", "| Consumer | Provider | Type | Strength | Reason |", "|---|---|---|---|---|");
  for (const edge of edges) {
    lines.push(`| \`${edge.from}\` | \`${edge.to}\` | ${edge.type} | ${edge.strength} | ${edge.reason} |`);
  }
  lines.push("");
  return lines.join("\n");
}

const { modules, edges } = await loadModuleMap();
const expected = renderGraph(modules, edges);

if (checkOnly) {
  let actual = "";
  try {
    actual = await readFile(outputPath, "utf8");
  } catch {
    // A missing graph is treated exactly like a stale graph below.
  }
  if (actual.replaceAll("\r\n", "\n") !== expected) {
    console.error("Module graph is stale. Run: npm.cmd run module-map:generate");
    process.exitCode = 1;
  } else {
    console.log("PASS module graph is current");
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected, "utf8");
  console.log("Generated docs/architecture/module-graph.md");
}
